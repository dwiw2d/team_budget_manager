// CLOVA General OCR 응답의 images[0].fields 모양으로 손으로 옮긴 것.
// 좌표는 실제 픽셀이 아니라 배치만 맞춘 값이다(위->아래, 왼->오른쪽).
// 실제 응답을 받으면 .local/ 에 저장한 원본으로 이 파일을 갈아끼우면 된다.

// [text, x] 목록과 줄 위치로 fields 를 만든다. 폭은 글자 수 * 높이 * 0.6 으로 어림잡는다.
function line(top, height, words) {
  return words.map(([text, x], i) => {
    const w = Math.round(text.length * height * 0.6);
    return {
      valueType: 'ALL',
      inferText: text,
      inferConfidence: 0.99,
      type: 'NORMAL',
      lineBreak: i === words.length - 1,
      boundingPoly: {
        vertices: [
          { x, y: top },
          { x: x + w, y: top },
          { x: x + w, y: top + height },
          { x, y: top + height },
        ],
      },
    };
  });
}

